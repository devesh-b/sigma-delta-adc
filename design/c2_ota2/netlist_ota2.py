#!/usr/bin/env python3
"""C2 OTA2 netlist generator (WO-98, D91). Builds the OTA1 cell through design/c1_ota1/netlist.py with the 9/16 sizes of
sizes_ota2.py, then drops the bias legs (references, replica, cascode-bias diodes, bank switch, V_BL0 replica): their
nets are ports and tie to OTA1's nets at the top level. Same port list as ota1:

  .subckt ota2 vdd vss inp inn outp outn vicm vocm ibtp ibn ibp ivbnc ivbpc ivbl0
  +            chp chn chlp chln isl ph1 ph1b ph2 ph2b rstb

  ibtp ibn ibp ivbnc ivbpc ivbl0  INPUTS here: OTA1's bias nets (gate-only loads; ivbl0 = CMFB clamp/refresh level)
  chp chn chlp chln               unused with chop=False (default; OTA2 is not chopped, SPEC): inp->gp, inn->gm, fa->xa,
                                  fb->xb wired by 0 V sources. Tie them to a rail at the top.
  isl ph1 ph1b ph2 ph2b rstb      as ota1 (island shunt, own SC CMFB phases, start-up clamps)

    python netlist_ota2.py [OUT.spice]     # writes the cmfb="sc" subckt (default: design/c2_ota2/ota2.spice)

Options: cmfb "sc" | "dc" (as netlist.py), mut tokens passed to netlist.py (nc_short, cm_open, int_off, cc_div4) plus
tail_half (OTA2 tail 9 fingers, broken copy), vt = {instance: dVT [V]} series gate sources (hand Pelgrom MC).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "c1_ota1"))
import netlist as NL  # noqa: E402
import sizes_ota2 as S2  # noqa: E402

PORTS = NL.PORTS
BIAS_INST = ("mtr", "mnr", "mplr", "mbpd", "mbpds", "mbnd", "Sbkn", "Sbkp", "mbku", "mrcp", "mrcb", "mrt", "mrnc", "mrn",
             "mbpx", "mbpxs", "mbl0")
CHOP_INST = ("Sci1", "Sci2", "Sci3", "Sci4", "Scf1", "Scf2", "Scf3", "Scf4")
NL_TOKS = ("nc_short", "cm_open", "int_off", "cc_div4")


def build(name="ota2", cmfb="sc", fs=4e6, mut=None, vt=None, chop=False):
    t = NL.toks(mut)
    z = {k: dict(v) for k, v in (NL.S.SIZES if "ota1cell" in t else S2.SIZES).items()}   # ota1cell: diagnostic, full OTA1 cell in the slot
    if "tail_half" in t:
        z["m_t"]["M"] //= 2
    mut1 = "+".join(sorted(x for x in t if x in NL_TOKS)) or None
    txt = NL.build(name, cmfb=cmfb, fs=fs, mut=mut1, sizes=z, boost=False)
    drop = BIAS_INST + (() if chop else CHOP_INST)
    out, seen = [], set()
    for ln in txt.splitlines():
        tok = ln.split()
        inst = tok[0][1:] if tok and tok[0][0] == "X" else None
        if inst in drop:
            seen.add(inst)
            continue
        if vt and inst in vt:
            g = tok[2]
            tok[2] = f"g_{inst}"
            out += [" ".join(tok), f"Vvt_{inst} g_{inst} {g} {vt[inst]:.6g}"]
            continue
        if ln.startswith(".ends") and not chop:
            out += ["Vwi1 inp gp 0", "Vwi2 inn gm 0", "Vwf1 fa xa 0", "Vwf2 fb xb 0"]
        out.append(ln)
    missing = set(drop) - seen
    assert not missing, f"netlist.py instance names changed, not dropped: {missing}"
    out[0] = (f"* OTA2 (generated by design/c2_ota2/netlist_ota2.py from sizes_ota2.py via c1_ota1/netlist.py; cmfb={cmfb}, "
              f"mut={mut}, chop={chop}, vt={'yes' if vt else 'no'}) - do not edit. Bias nets are inputs (OTA1's).")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    fn = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "ota2.spice")
    open(fn, "w").write(build())
    print(fn)
